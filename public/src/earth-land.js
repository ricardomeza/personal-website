const COLS = 360;
const ROWS = 180;
let mask = null;

function decode() {
  const cells = new Uint8Array(COLS * ROWS);
  let cell = 0;
  let rowEnd = COLS;
  let land = 0;
  for (let i = 0; i < RUNS.length; i += 2) {
    const run = parseInt(RUNS.slice(i, i + 2), 36);
    if (land) cells.fill(1, cell, cell + run);
    cell += run;
    land ^= 1;
    if (cell === rowEnd) {
      rowEnd += COLS;
      land = 0;
    }
  }
  return cells;
}

// Latitude and longitude in degrees.
export function isLand(lat, lon) {
  mask ??= decode();
  const row = Math.min(ROWS - 1, Math.max(0, Math.floor(90 - lat)));
  const col = ((Math.floor(lon + 180) % COLS) + COLS) % COLS;
  return mask[row * COLS + col] === 1;
}
